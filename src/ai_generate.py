import os
import json
from datetime import datetime

from openai import OpenAI


# ============================================================
# 설정
# ============================================================

OPENAI_API_KEY = os.environ["OPENAI_API_KEY"]

INPUT_FILE = "data/raw_news.json"
OUTPUT_FILE = "data/news.json"

MODEL = "gpt-5.6-luna"


# ============================================================
# OpenAI 클라이언트
# ============================================================

client = OpenAI(
    api_key=OPENAI_API_KEY
)


# ============================================================
# 뉴스 데이터 읽기
# ============================================================

def load_news():

    with open(
        INPUT_FILE,
        "r",
        encoding="utf-8"
    ) as f:

        data = json.load(f)

    return data


# ============================================================
# AI 프롬프트
# ============================================================

SYSTEM_PROMPT = """

당신은 삼성화재 강원영업단의 RC를 위한
매일 아침 보험·의료 뉴스 브리핑을 만드는
전문 콘텐츠 편집자입니다.

목표는 단순한 뉴스 요약이 아니라
삼성화재 RC가 실제 고객 상담과 영업활동에
활용할 수 있는 뉴스를 선별하는 것입니다.

다음 원칙을 반드시 지키세요.

[1. 대상 독자]

삼성화재 RC입니다.

본문에서는
FP, FC, 설계사라는 표현을 사용하지 말고
반드시 "RC"라는 표현을 사용하세요.

[2. 우선순위]

다음 순서로 중요한 뉴스를 우선합니다.

1순위:
보험 제도·정책 변화

2순위:
병원비·의료비·비급여·건강보험 관련 이슈

3순위:
신의료기술·치료기술·질병 관련 의료 이슈

4순위:
삼성화재 장기보장성 보험 및 서비스와
연결할 수 있는 뉴스

[3. 제외]

다음 뉴스는 선정하지 마세요.

- 주식 시세
- 주가
- 영업이익
- 순이익
- 실적
- 투자 관련 기사
- 자동차보험
- 휴대폰보험
- 여행자보험
- 일반 단기손해보험
- 펫보험
- 보험영업 실적 기사

단,

건강보험, 어린이보험, 실손보험,
간병보험, 암보험, 뇌혈관질환,
심혈관질환, 중증질환 등
장기보장성 보험과 관련성이 높은 내용은
적극적으로 고려하세요.

[4. 삼성화재 관련 기사]

삼성화재에 관한 뉴스는
장기보장성 보험이나 고객 서비스,
건강·의료 관련 상품과 연결되는 경우
우선적으로 고려하세요.

단순 주가·실적 뉴스는 제외합니다.

[5. 영업 Tip]

각 기사마다 RC가 고객과 대화할 때
실제로 사용할 수 있는 한 가지 영업 Tip을
작성하세요.

과장된 보험 판매 문구를 만들지 마세요.

기사 내용을 근거로
자연스럽게 고객에게 질문하거나
대화를 시작할 수 있는 방식으로 작성하세요.

[6. 기사 요약]

기사 원문을 그대로 복사하지 마세요.

핵심 내용을 2~3문장으로
재구성해서 요약하세요.

[7. 사실성]

입력된 기사에 없는 내용을
사실처럼 만들어내지 마세요.

기사에서 확인되지 않는 내용은
추측하지 마세요.

"""


# ============================================================
# AI 호출
# ============================================================

def generate_news(selected_articles):

    user_prompt = """

아래 뉴스 목록을 분석해서
삼성화재 강원영업단 RC 아침 브리핑에
사용할 가치가 높은 기사들을 선별하세요.

이번 테스트에서는
카테고리별로 최대 3개까지 선정합니다.

카테고리:

1. 제도 동향
2. 의료비 이슈
3. 삼성화재 소식

각 기사에는 다음 정보를 작성하세요.

- title
- published_at
- source_url
- category
- summary
- why_it_matters
- sales_tip

그리고 마지막에

오늘의 영업 포인트 3개를 작성하세요.

반드시 JSON 형식으로만 답변하세요.

뉴스 목록:

""" + json.dumps(
        selected_articles,
        ensure_ascii=False,
        indent=2
    )

    response = client.responses.create(

        model=MODEL,

        instructions=SYSTEM_PROMPT,

        input=user_prompt

    )

    return response.output_text


# ============================================================
# 메인
# ============================================================

def main():

    print("=" * 60)

    print(
        "OpenAI 뉴스 분석 시작"
    )

    print("=" * 60)


    # 뉴스 불러오기

    data = load_news()

    articles = data.get(
        "articles",
        []
    )


    print(
        f"전체 수집 뉴스: {len(articles)}개"
    )


    # --------------------------------------------------------
    # 테스트에서는 최대 80개만 AI에게 전달
    # --------------------------------------------------------

    selected_articles = articles[:80]


    print(
        f"AI 분석 대상: {len(selected_articles)}개"
    )


    # --------------------------------------------------------
    # OpenAI 호출
    # --------------------------------------------------------

    result = generate_news(
        selected_articles
    )


    print()
    print("=" * 60)
    print("OpenAI 응답")
    print("=" * 60)

    print(result)


    # --------------------------------------------------------
    # JSON 변환
    # --------------------------------------------------------

    try:

        parsed = json.loads(
            result
        )

    except json.JSONDecodeError:

        print()
        print(
            "⚠️ OpenAI 응답이 JSON 형식이 아닙니다."
        )

        # 테스트 결과 확인용
        parsed = {
            "raw_response": result
        }


    # --------------------------------------------------------
    # 날짜 추가
    # --------------------------------------------------------

    output = {

        "generated_at":
            datetime.now().astimezone().isoformat(),

        "model":
            MODEL,

        "data":
            parsed

    }


    # --------------------------------------------------------
    # news.json 저장
    # --------------------------------------------------------

    os.makedirs(
        "data",
        exist_ok=True
    )


    with open(

        OUTPUT_FILE,

        "w",

        encoding="utf-8"

    ) as f:

        json.dump(

            output,

            f,

            ensure_ascii=False,

            indent=2

        )


    print()
    print("=" * 60)

    print(
        f"파일 생성: {OUTPUT_FILE}"
    )

    print("=" * 60)


# ============================================================
# 실행
# ============================================================

if __name__ == "__main__":

    main()
