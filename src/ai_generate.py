# ============================================================
# 메인
# ============================================================

def main():

    print("=" * 60)
    print("Gemini 뉴스 분석 시작")
    print("=" * 60)


    # 뉴스 불러오기

    data = load_news()

    articles = data.get(
        "articles",
        []
    )


    print(
        f"전체 수집 뉴스: {len(articles)}개"
    )


    # --------------------------------------------------------
    # 테스트 단계
    # 우선 80개만 분석
    # --------------------------------------------------------

    selected_articles = articles[:80]


    print(
        f"AI 분석 대상: {len(selected_articles)}개"
    )


    # --------------------------------------------------------
    # Gemini 호출
    # --------------------------------------------------------

    result = generate_news(
        selected_articles
    )


    print()
    print("=" * 60)
    print("Gemini 응답")
    print("=" * 60)

    print(result)


    # --------------------------------------------------------
    # JSON 변환
    # --------------------------------------------------------

    try:

        parsed = json.loads(result)

    except json.JSONDecodeError:

        print()
        print(
            "ERROR: Gemini 응답이 JSON 형식이 아닙니다."
        )

        raise


    # --------------------------------------------------------
    # 최종 데이터
    # --------------------------------------------------------

    output = {

        "generated_at":
            datetime.now().astimezone().isoformat(),

        "model":
            MODEL,

        "data":
            parsed

    }


    # --------------------------------------------------------
    # 저장
    # --------------------------------------------------------

    os.makedirs(
        "data",
        exist_ok=True
    )


    with open(

        OUTPUT_FILE,

        "w",

        encoding="utf-8"

    ) as f:

        json.dump(

            output,

            f,

            ensure_ascii=False,

            indent=2

        )


    print()
    print("=" * 60)
    print(
        f"파일 생성: {OUTPUT_FILE}"
    )
    print("=" * 60)


# ============================================================
# 실행
# ============================================================

if __name__ == "__main__":

    main()
